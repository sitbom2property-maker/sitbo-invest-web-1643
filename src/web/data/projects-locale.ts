function localizeCompletion(value: string): string {
  return value
    .replace(/\bQ1\b/g, "I кв.")
    .replace(/\bQ2\b/g, "II кв.")
    .replace(/\bQ3\b/g, "III кв.")
    .replace(/\bQ4\b/g, "IV кв.");
}

