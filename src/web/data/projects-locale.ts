export function localizeProject(p: Project, language: string): Project {
  const lang = language.toLowerCase().startsWith("ru") ? "ru" : "en";
  if (lang !== "ru") return p;
  const ru = projectRuBySlug[p.slug];
  const merged = ru ? { ...p, ...ru } : { ...p };
  if (!ru?.completion) {
    merged.completion = localizeCompletion(merged.completion);
  }
  return merged;
}

export function localizeProjects(list: Project[], language: string): Project[] {
  return list.map((p) => localizeProject(p, language));
}

const CITY_RU: Record<string, string> = {
  Batumi: "Батуми",
  Tbilisi: "Тбилиси",
  "Chakvi / Gonio": "Чакви / Гонио",
  Makhinjauri: "Махинджаури",
};

export function localizeCityLabel(city: string, language: string): string {
  if (!language.toLowerCase().startsWith("ru")) return city;
  return CITY_RU[city] ?? city;
}
